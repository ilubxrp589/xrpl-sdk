#!/usr/bin/env python3
"""Generate src/crypto/wordlists.rs: the BIP-39 English word list and the
RFC 1751 dictionary, each checked against the SHA-256 of its source.

Sources:
  BIP-39:   https://github.com/bitcoin/bips/blob/master/bip-0039/english.txt
  RFC 1751: rippled 3.4.1 src/libxrpl/crypto/RFC1751.cpp (`RFC1751::dictionary`)

Usage: gen_wordlists.py ENGLISH_TXT RFC1751_CPP > src/crypto/wordlists.rs
"""
import hashlib
import re
import sys

BIP39_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"


def bip39(path):
    raw = open(path, "rb").read()
    assert hashlib.sha256(raw).hexdigest() == BIP39_SHA256, "not the BIP-39 English list"
    words = raw.decode().split()
    assert len(words) == 2048 and words == sorted(words)
    return words


def rfc1751(path):
    src = open(path).read()
    body = src[src.index("RFC1751::dictionary[2048]"):]
    body = body[: body.index("};")]
    words = re.findall(r'"([A-Z]+)"', body)
    assert len(words) == 2048
    # rippled searches words of 1-3 letters in [0, 571) and 4 letters in [571, 2048).
    assert all(len(w) < 4 for w in words[:571]) and all(len(w) == 4 for w in words[571:])
    assert words[:571] == sorted(words[:571]) and words[571:] == sorted(words[571:])
    return words


def table(name, doc, words):
    lines = [f"/// {d}" for d in doc]
    lines.append("#[rustfmt::skip]")
    lines.append(f"pub(crate) static {name}: [&str; 2048] = [")
    for i in range(0, 2048, 8):
        lines.append("    " + " ".join(f'"{w}",' for w in words[i:i + 8]))
    lines.append("];")
    return "\n".join(lines)


def main():
    english = bip39(sys.argv[1])
    dictionary = rfc1751(sys.argv[2])
    print("// @generated by scripts/gen_wordlists.py. Do not edit by hand.")
    print("//! Word lists for the mnemonic encodings.")
    print()
    print(table("BIP39_ENGLISH", [
        "The BIP-39 English word list, in order (index = 11-bit value).",
        f"SHA-256 of the source file: {BIP39_SHA256}.",
    ], english))
    print()
    print(table("RFC1751_WORDS", [
        "The RFC 1751 dictionary, as `rippled` 3.4.1 has it (index = 11-bit value):",
        "words of one to three letters at 0..571, four letters at 571..2048, each",
        "range sorted.",
    ], dictionary))


main()
