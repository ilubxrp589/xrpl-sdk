def doc(name, rippled_type, required):
    """One doc line for a generated field."""
    phrase = TYPE_PHRASE.get(rippled_type, rippled_type or "JSON")
    need = "Required." if required else "Optional."
    if name in MEANING:
        return f"/// {MEANING[name]} (`{name}`: {phrase}). {need}"
    return f"/// `{name}`: {phrase}. {need}"
